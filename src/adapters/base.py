"""Adapters own native behavior; evaluation and ownership stay outside."""
from abc import ABC,abstractmethod


class BaseParserAdapter(ABC):
    @abstractmethod
    def load(self): ...
    @abstractmethod
    def describe_model(self): ...
    @abstractmethod
    def preprocess(self,sample): ...
    @abstractmethod
    def infer(self,prepared_input): ...
    @abstractmethod
    def postprocess(self,raw_output): ...
    @abstractmethod
    def export_prediction(self,prediction): ...
    @abstractmethod
    def cleanup(self): ...
